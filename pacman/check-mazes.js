let fail = 0;
for (const [name, rows] of Object.entries(MAZES)) {
  if (rows.length !== 31) {
    console.log(`${name}: FAIL ${rows.length} rows`);
    fail++;
    continue;
  }
  let widthOk = true;
  rows.forEach((r, i) => {
    if (r.length !== 28) {
      console.log(`${name}: row ${i} has ${r.length} cols`);
      widthOk = false;
    }
  });
  if (!widthOk) {
    fail++;
    continue;
  }

  const walkable = (x, y) => {
    if (y < 0 || y >= 31) return false;
    x = (x + 28) % 28;
    const c = rows[y][x];
    return c !== "#" && c !== "-";
  };
  if (!walkable(14, 23)) {
    console.log(`${name}: FAIL pacman start blocked`);
    fail++;
  }
  if (!walkable(13, 11)) {
    console.log(`${name}: FAIL blinky spawn blocked`);
    fail++;
  }

  const seen = new Set();
  const stack = [[14, 23]];
  while (stack.length) {
    const [x0, y0] = stack.pop();
    const x = ((x0 % 28) + 28) % 28; // normalize for wrap-around tunnels
    const y = ((y0 % 31) + 31) % 31;
    const key = `${x},${y}`;
    if (seen.has(key) || !walkable(x, y)) continue;
    seen.add(key);
    stack.push([x + 1, y], [x - 1, y], [x, y + 1], [x, y - 1]);
  }
  let unreachable = [],
    pellets = 0,
    power = 0;
  for (let y = 0; y < 31; y++)
    for (let x = 0; x < 28; x++) {
      const c = rows[y][x];
      if (c === "." || c === "o") {
        c === "o" ? power++ : pellets++;
        if (!seen.has(`${x},${y}`)) unreachable.push(`(${x},${y})`);
      }
    }
  if (unreachable.length) {
    console.log(`${name}: FAIL unreachable: ${unreachable.join(" ")}`);
    fail++;
  }
  if (power !== 4) {
    console.log(`${name}: FAIL ${power} power pellets (want 4)`);
    fail++;
  }
  if (!unreachable.length && power === 4)
    console.log(`${name}: OK (${pellets + power} pellets, all reachable)`);
}
process.exit(fail ? 1 : 0);
